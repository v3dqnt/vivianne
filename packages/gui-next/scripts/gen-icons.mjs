// Regenerates src/iconGlyphs.ts: the Solar glyph data for exactly the icons
// src/icons.ts uses, so builds don't parse the whole 8,000-icon set.
// Solar (c) 480 Design, CC BY 4.0, via @iconify-json/solar. Run after adding an
// icon to icons.ts:  npm run icons -w gui-next
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const data = require('@iconify-json/solar/icons.json')

const source = readFileSync(join(here, '../src/icons.ts'), 'utf8')
const wanted = new Set()
for (const m of source.matchAll(/\bicon\('([\w-]+)'(?:,\s*'(linear|bold)')?\)/g)) wanted.add(`${m[1]}-${m[2] ?? 'linear'}`)

const missing = [...wanted].filter((n) => !data.icons[n])
if (missing.length) {
  console.error(`Not in Solar: ${missing.join(', ')}`)
  process.exit(1)
}
const names = [...wanted].sort()
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(data.icons[n].body)},`).join('\n')
writeFileSync(
  join(here, '../src/iconGlyphs.ts'),
  `// Generated by scripts/gen-icons.mjs from @iconify-json/solar (Solar icons by 480 Design, CC BY 4.0).
// Do not edit by hand.
export const solar: Record<string, string> = {
${body}
}
`,
)
console.log(`Wrote ${names.length} glyphs to src/iconGlyphs.ts`)
