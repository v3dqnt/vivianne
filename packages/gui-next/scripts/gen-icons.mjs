// Regenerates src/iconGlyphs.ts: the Hugeicons glyph data for exactly the
// icons src/icons.ts uses. The full @hugeicons/core-free-icons barrel is
// ~15k icons, and importing from it makes every build parse all of them;
// vendoring the few dozen we use keeps builds fast. Run after adding an
// icon to icons.ts:  npm run icons -w gui-next
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const icons = require('@hugeicons/core-free-icons')

const source = readFileSync(join(here, '../src/icons.ts'), 'utf8')
const names = [...new Set([...source.matchAll(/\bicon\(G\.(\w+Icon)\)/g)].map((m) => m[1]))].sort()

const missing = names.filter((n) => !icons[n])
if (missing.length) {
  console.error(`Not in @hugeicons/core-free-icons: ${missing.join(', ')}`)
  process.exit(1)
}

const body = names.map((n) => `export const ${n}: IconSvgElement = ${JSON.stringify(icons[n])}`).join('\n')
writeFileSync(
  join(here, '../src/iconGlyphs.ts'),
  `// Generated by scripts/gen-icons.mjs from @hugeicons/core-free-icons (MIT).
// Do not edit by hand.
import type { IconSvgElement } from '@hugeicons/react'

${body}
`,
)
console.log(`Wrote ${names.length} glyphs to src/iconGlyphs.ts`)
