// Writes index.html from scenes.json: one sub-composition host per scene,
// laid end to end, plus a muted <video> under any scene whose footage file
// exists. Add a scene by adding a file in compositions/ and an entry here.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/'/g, '&#39;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/** Scenes with start times: each starts where the previous one ended. */
export function layout(manifest) {
  let start = 0
  return manifest.scenes.map((s) => {
    const placed = { ...s, start, variables: s.variables ?? {} }
    start += s.duration
    return placed
  })
}

export function buildIndex(manifest, { exists }) {
  const scenes = layout(manifest)
  for (const s of scenes) if (!exists(s.src)) throw new Error(`scenes.json: composition not found: ${s.src}`)
  const total = scenes.reduce((n, s) => n + s.duration, 0)
  const { width, height } = manifest

  const clips = scenes.flatMap((s) => {
    const hasFootage = Boolean(s.footage && exists(s.footage))
    const vars = esc(JSON.stringify({ ...s.variables, hasFootage }))
    const out = []
    if (hasFootage)
      out.push(
        `      <video id="${s.id}-footage" class="clip footage" src="${s.footage}" muted playsinline data-start="${s.start}" data-duration="${s.duration}" data-track-index="0"></video>`,
      )
    out.push(
      `      <div id="${s.id}" class="clip scene" data-composition-id="${s.id}" data-composition-src="${s.src}" data-start="${s.start}" data-duration="${s.duration}" data-track-index="1" data-variable-values="${vars}"></div>`,
    )
    return out
  })

  return `<!doctype html>
<!-- Generated by scripts/build.mjs from scenes.json. Do not edit by hand. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/tokens.css" />
    <link rel="stylesheet" href="assets/app.css" />
    <script src="assets/motion.js"></script>
    <script src="assets/story.js"></script>
${(manifest.captures ?? []).map((c) => `    <script src="captures/${c}.js"></script>`).join('\n')}
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${width}px; height: ${height}px; overflow: hidden; background: #000; }
      .clip { position: absolute; inset: 0; width: 100%; height: 100%; }
      .footage { object-fit: cover; z-index: 0; }
      .scene { z-index: 1; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="${width}" data-height="${height}">
${clips.join('\n')}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const manifest = JSON.parse(readFileSync(join(root, 'scenes.json'), 'utf8'))
  writeFileSync(join(root, 'index.html'), buildIndex(manifest, { exists: (p) => existsSync(join(root, p)) }))
  console.log(`index.html: ${manifest.scenes.length} scenes`)
}
