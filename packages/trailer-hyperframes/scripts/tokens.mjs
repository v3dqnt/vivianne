// Generates assets/tokens.css from the app's own theme source
// (packages/gui-next/src/theme.ts), so the trailer's colours are the app's.
// theme.ts is parsed rather than imported: importing it pulls in MUI and CSS.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const THEME = join(here, '../../gui-next/src/theme.ts')

/** The dark neutral token set (the default "Monochrome" palette, id `terax`). */
export function darkTokens(src = readFileSync(THEME, 'utf8')) {
  const neutral = src.slice(src.indexOf('const NEUTRAL'))
  const block = neutral.slice(neutral.indexOf('dark: {') + 7)
  const body = block.slice(0, block.indexOf('}'))
  const tokens = {}
  for (const m of body.matchAll(/(\w+):\s*'([^']+)'/g)) tokens[m[1]] = m[2]
  return tokens
}

/** `ui/theme.ts` frameOf: card mixed 97/3 toward foreground. */
export function frameOf(card, fg) {
  const p = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
  const [x, y] = [p(card), p(fg)]
  return `#${x.map((v, i) => Math.round(v * 0.97 + y[i] * 0.03).toString(16).padStart(2, '0')).join('')}`
}

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

export async function tokensCss() {
  const t = darkTokens()
  t.frame = frameOf(t.card, t.foreground)
  const lines = Object.entries(t).map(([k, v]) => `  --${kebab(k)}: ${v};`)
  return `/* Generated by scripts/tokens.mjs from packages/gui-next/src/theme.ts (dark, Monochrome). Do not edit. */
:root {
${lines.join('\n')}
  --surface-radius: 14px;
  --radius: 10px;
  --font-ui: "Geist", system-ui, -apple-system, "Segoe UI", sans-serif;
  --font-mono: "Geist Mono", ui-monospace, "Cascadia Code", monospace;
  --font-display: "Sora", "Geist", sans-serif;
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, '../assets/tokens.css'), await tokensCss())
  console.log('assets/tokens.css written')
}
